/**
 * Generate SYNTHETIC reviewer decisions (draft → reviewer action) to seed the learning loop.
 * Output: data/synthetic/review_decisions.json (committed, so everyone seeds the same history).
 * You normally do NOT need to run this again. Run: npm run gen:decisions
 *
 * Each decision follows a planned correction pattern, so the rules ECHO later extracts
 * are predictable enough to demo, but the text is varied.
 */
import fs from "node:fs";
import "./_env";
import { chatJSON } from "@/lib/ai";

const TOPICS = [
  "welcoming a new cohort", "career switching into tech at 35+", "mentor spotlight", "a day in week 3 of training",
  "employed from Day 1 model", "Java full-stack track", "data and AI track", "award win announcement",
  "hiring partner thank-you", "graduation of a cohort", "applications closing soon", "why local talent pipelines matter",
];

// pattern → what the AI draft does wrong, and what the reviewer does about it
const PLAN: { pattern: string; action: "edited" | "approved" | "rejected"; n: number; reason?: string }[] = [
  { pattern: "Draft OPENS WITH A QUESTION. Reviewer rewrites the first line as a direct statement.", action: "edited", n: 6 },
  { pattern: "Draft has 6-10 hashtags. Reviewer cuts to at most 3 relevant ones.", action: "edited", n: 5 },
  { pattern: "Draft uses hype words (revolutionary, game-changing, unlock, journey). Reviewer replaces them with plain words.", action: "edited", n: 5 },
  { pattern: "Draft has no link or call to action. Reviewer adds 'Apply at upskilltoday.com' or similar.", action: "edited", n: 4 },
  { pattern: "Draft is long (200+ words). Reviewer cuts it to under 120 words, keeping the key fact.", action: "edited", n: 4 },
  { pattern: "Draft promises salaries or placement rates. Reviewer rejects it.", action: "rejected", n: 3, reason: "wrong_claim" },
  { pattern: "Draft sounds like a generic motivational poster, not the brand. Reviewer rejects it.", action: "rejected", n: 2, reason: "off_brand_tone" },
  { pattern: "Draft repeats a welcome post the page already published this month. Reviewer rejects it.", action: "rejected", n: 1, reason: "duplicate" },
  { pattern: "Draft is already good: statement opener, <=3 hashtags, plain words, has a link. Reviewer approves unchanged.", action: "approved", n: 6 },
];

type Out = { decisions: { topic: string; draft: string; final: string | null; note: string | null }[] };

async function main() {
  const all: unknown[] = [];
  let t = 0;
  for (const p of PLAN) {
    const topics = Array.from({ length: p.n }, () => TOPICS[t++ % TOPICS.length]);
    const out = await chatJSON<Out>([
      {
        role: "system",
        content:
          "You create realistic SYNTHETIC training data for a LinkedIn content tool used by Upskill Today, a tech-talent " +
          "accelerator (GECO Asia division) that hires mid-career switchers and graduates from Day 1 and trains them for enterprise projects. " +
          "Write the AI DRAFT exactly as described in the pattern, then the reviewer's FINAL. Do not invent statistics. " +
          'Return JSON {"decisions":[{"topic":"…","draft":"…","final":"… or null if rejected/approved","note":"short reviewer note if rejected, else null"}]}',
      },
      { role: "user", content: `PATTERN: ${p.pattern}\nACTION: ${p.action}\nTOPICS (one decision each): ${topics.join(" | ")}` },
    ], { maxTokens: 6000, temperature: 0.9 });
    for (const d of out.decisions.slice(0, p.n)) {
      all.push({
        topic: d.topic,
        pattern: p.pattern.split(".")[0],
        status: p.action,
        draft: d.draft,
        final: p.action === "edited" ? d.final : p.action === "approved" ? d.draft : null,
        decision_reason: p.reason ?? null,
        decision_note: p.action === "rejected" ? d.note : null,
      });
    }
    console.log(`› ${p.action.padEnd(8)} ${out.decisions.length} × ${p.pattern.slice(0, 60)}`);
  }
  fs.writeFileSync(
    "data/synthetic/review_decisions.json",
    JSON.stringify({ source: "synthetic", note: "Generated by scripts/generate-decisions.ts for the ECHO prototype. Not real reviewer decisions.", decisions: all }, null, 2),
  );
  console.log(`› wrote ${all.length} decisions`);
}

main().catch((e) => {
  console.error("✗", e.message ?? e);
  process.exit(1);
});
